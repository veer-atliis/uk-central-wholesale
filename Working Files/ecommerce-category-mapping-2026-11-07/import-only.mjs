import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {pathToFileURL,fileURLToPath} from 'node:url';
const require=createRequire('C:/Program Files/WindowsApps/OpenAI.CodexPrimaryRuntime.v26-1104-2876-0_26.1104.2876.0_x64__3k8sg7r9htsxt/dependencies/node/package.json');
const {Workbook,SpreadsheetFile}=await import(pathToFileURL(require.resolve('@oai/artifact-tool')).href);
const dir=new URL('.',import.meta.url);
const read=async name=>JSON.parse(await fs.readFile(new URL(name,dir),'utf8'));
const ids=(await read('external-ids.json')).Sheet1.slice(1);
const populated=(await read('populated.json')).slice(1);
const websites=(await read('sources.json'))['Website Product Category (product.public.category).xlsx'].Sheet1.slice(1);
const key=r=>String(r??'');
if(new Set(ids.map(r=>r[0])).size!==ids.length) throw Error('Duplicate external IDs');
if(new Set(ids.map(r=>key(r[3]))).size!==ids.length) throw Error('Duplicate exported references');
if(new Set(populated.map(r=>key(r[1]))).size!==populated.length) throw Error('Duplicate product references');
if(ids.length!==populated.length) throw Error('Product count mismatch');
const rows=[['External ID','Website Product Category/External ID','Control Policy']];
for(const r of populated){
 const match=ids.filter(x=>key(x[3])===key(r[1]));
 if(match.length!==1||match[0][2]!==r[0]||!match[0][0]) throw Error(`Product match failed: ${r[1]}`);
 const cat=websites.filter(x=>x[3]===r[7]);
 if(cat.length!==1||!cat[0][0]) throw Error(`Category match failed: ${r[7]}`);
 if(r[8]!=='purchase') throw Error(`Unexpected control policy: ${r[1]}`);
 rows.push([match[0][0],cat[0][0],r[8]]);
}
const wb=Workbook.create();
const s=wb.worksheets.add('Products');
s.getRange(`A1:C${rows.length}`).values=rows;
s.getRange(`A1:C${rows.length}`).setNumberFormat('@');
s.getRange(`A1:C${rows.length}`).format.font.name='Arial';
s.getRange(`A1:C${rows.length}`).format.font.size=10;
s.getRange('A1:C1').format.font.bold=true;
s.getRange('A:A').format.columnWidth=51;
s.getRange('B:B').format.columnWidth=58;
s.getRange('C:C').format.columnWidth=20;
s.freezePanes.freezeRows(1);
wb.recalculate();
if(JSON.stringify(s.getRange(`A1:C${rows.length}`).values)!==JSON.stringify(rows)) throw Error('Output verification failed');
const blob=await wb.render({sheetName:'Products',range:'A1:C7',scale:1.5,format:'png'});
await fs.writeFile(new URL('import-only-preview.png',dir),new Uint8Array(await blob.arrayBuffer()));
const output=new URL('../../Output/outputs/ecommerce-category-mapping-2026-11-07/Products - ecommerce and control policy import.xlsx',dir);
await (await SpreadsheetFile.exportXlsx(wb)).save(fileURLToPath(output));
console.log(JSON.stringify({products:rows.length-1,columns:rows[0],matching:'Unique internal reference and exact name confirmed for every product',categories:'Existing website category External IDs',policy:'purchase on all 128 products',output:fileURLToPath(output)}));
